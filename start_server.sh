#!/usr/bin/env bash

# Цвета для красивого вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Переходим в папку, где лежит сам скрипт (аналог cd /d "%~dp0")
cd "$(dirname "$0")" || exit

echo -e "${CYAN}============================================================${NC}"
echo -e "${CYAN}  ЗАПУСК СЕРВЕРА PYTHON VS SPORT${NC}"
echo -e "${CYAN}============================================================${NC}"
echo ""

# --- Проверка прав администратора ---
if [ "$EUID" -ne 0 ]; then
    echo -e "${YELLOW}[ВНИМАНИЕ] Скрипт запущен без прав администратора (root).${NC}"
    echo -e "${YELLOW}Для корректной работы сервера и работы сетевых портов нужны права root.${NC}"
    echo -e "${YELLOW}Сейчас система запросит ваш пароль (sudo).${NC}"
    echo ""
    # Перезапускаем скрипт с правами sudo
    exec sudo "$0" "$@"
fi

# --- Мы в режиме администратора ---

# Проверка виртуального окружения
if [ ! -f ".venv/bin/python" ]; then
    echo -e "${RED}[ОШИБКА] Не найдено виртуальное окружение .venv!${NC}"
    echo "Пожалуйста, убедитесь, что скрипт лежит в корне проекта."
    read -r -p "Нажмите Enter для выхода..."
    exit 1
fi

# Проверка файла запуска
if [ ! -f "web/run.py" ]; then
    echo -e "${RED}[ОШИБКА] Не найден файл web/run.py!${NC}"
    read -r -p "Нажмите Enter для выхода..."
    exit 1
fi

echo -e "${GREEN}[ИНФО] Запускаем сервер...${NC}"
echo -e "${GREEN}[ИНФО] Браузер откроется автоматически (если есть графическая оболочка).${NC}"
echo -e "${GREEN}[ИНФО] Для остановки нажмите Ctrl+C.${NC}"
echo ""

# Переходим в папку web и запускаем сервер
cd web || exit
"../.venv/bin/python" run.py

# Если сервер упал или был остановлен
echo ""
echo "Сервер остановлен."
read -r -p "Нажмите Enter для выхода..."
exit 0